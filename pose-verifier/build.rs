//! Builds the C this verifier shares with the daemons, so the two sides cannot
//! drift:
//!
//! - `pose-common` (graph + hash), through its own CMakeLists.txt, so the
//!   per-architecture flags (BLAKE3 SIMD backends, AES-NI / ARMv8 crypto) are
//!   exactly the daemons'.  Only the `pose_common` library target is built.
//! - `pose-sink/src/sink_proto.c`, the daemons' wire encoders, used by the
//!   tests to cross-check the Rust codec frame for frame.
//! - Every numeric and string `#define` of `pose-sink/include/sink_proto.h`
//!   becomes a Rust `pub const` in `$OUT_DIR/sink_proto_consts.rs`, so message
//!   types, kinds and limits (SINK_MAX_SESSIONS, ...) are defined only there.
//!   A plain line parser rather than bindgen: the header's defines are
//!   literals by convention, and it keeps libclang out of the build.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..");
    let common = root.join("pose-common");
    let sink = root.join("pose-sink");

    let dst = cmake::Config::new(&common)
        .profile("Release")
        .build_target("pose_common")
        .build();
    println!("cargo:rustc-link-search=native={}/build", dst.display());
    println!("cargo:rustc-link-lib=static=pose_common");
    println!("cargo:rustc-link-lib=pthread");

    cc::Build::new()
        .file(sink.join("src/sink_proto.c"))
        .include(sink.join("include"))
        .warnings(true)
        .compile("sink_proto");

    let header = sink.join("include/sink_proto.h");
    let text = std::fs::read_to_string(&header).expect("read sink_proto.h");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("sink_proto_consts.rs");
    std::fs::write(&out, consts_from_header(&text)).expect("write sink_proto_consts.rs");

    for dir in ["include", "src"] {
        println!("cargo:rerun-if-changed={}", common.join(dir).display());
    }
    println!("cargo:rerun-if-changed={}", common.join("CMakeLists.txt").display());
    println!("cargo:rerun-if-changed={}", sink.join("src/sink_proto.c").display());
    println!("cargo:rerun-if-changed={}", header.display());
}

/// `#define SINK_X <literal>` -> `pub const SINK_X: <type> = <literal>;`.
/// Integer literals (decimal or hex, optional u suffix) become u64, strings
/// &str, and `(A + B)` of two integers is folded.  Anything else is skipped
/// (and so cannot be used from Rust by accident).
fn consts_from_header(text: &str) -> String {
    let mut out = String::from("// Generated by build.rs from pose-sink/include/sink_proto.h.\n");
    for line in text.lines() {
        let Some(rest) = line.trim_start().strip_prefix("#define ") else { continue };
        let mut it = rest.splitn(2, char::is_whitespace);
        let (Some(name), Some(value)) = (it.next(), it.next()) else { continue };
        if !name.starts_with("SINK_") {
            continue;
        }
        let value = value.split("/*").next().unwrap().trim();
        if value.starts_with('"') {
            writeln!(out, "pub const {name}: &str = {value};").unwrap();
        } else if let Some(v) = eval_int(value) {
            writeln!(out, "pub const {name}: u64 = {v};").unwrap();
        }
    }
    out
}

fn eval_int(s: &str) -> Option<u64> {
    let s = s.trim();
    if let Some(inner) = s.strip_prefix('(').and_then(|s| s.strip_suffix(')')) {
        let (a, b) = inner.split_once('+')?;
        return Some(eval_int(a)? + eval_int(b)?);
    }
    let s = s.trim_end_matches(['u', 'U']);
    match s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
        Some(hex) => u64::from_str_radix(hex, 16).ok(),
        None => s.parse().ok(),
    }
}
