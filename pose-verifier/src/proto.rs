//! The tray wire protocol (pose-sink/include/sink_proto.h, normative) from the
//! verifier's side: it sends InventoryRequest, SessionInit, Challenge and
//! Finish to the source-daemon and receives everything else.  Framing is
//! `[u8 type][u32 len][payload]`, big-endian integers, `[u16 len]` strings.
//! Decoders are as strict as the C ones: short payloads, trailing bytes,
//! over-long strings and out-of-range counts are errors.

use anyhow::{bail, ensure, Context, Result};
use std::io::{Read, Write};
use std::net::TcpStream;
use std::time::Duration;

/// Every `#define SINK_*` literal of sink_proto.h (generated by build.rs).
#[allow(dead_code)]
pub mod c {
    include!(concat!(env!("OUT_DIR"), "/sink_proto_consts.rs"));
}

pub const LABEL_BYTES: usize = c::SINK_LABEL_BYTES as usize;
pub const SEED_BYTES: usize = c::SINK_SEED_BYTES as usize;
pub type Label = [u8; LABEL_BYTES];
pub type Seed = [u8; SEED_BYTES];

/// An inventory entry's kind: a target, or a RAM map entry (sink_proto.h, Flow 1).
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    Ram,
    Disk,
    Declared,
    Kernel,
    Reserved,
    Unusable,
    /// A GPU's labelable HBM ("gpuN", base 0).
    Gpu,
    /// A GPU's whole HBM.
    GpuDeclared,
    /// HBM held by the driver, or left as headroom.
    GpuReserved,
}

impl Kind {
    fn from_wire(v: u8) -> Result<Kind> {
        Ok(match v as u64 {
            c::SINK_TARGET_RAM => Kind::Ram,
            c::SINK_TARGET_DISK => Kind::Disk,
            c::SINK_RAM_DECLARED => Kind::Declared,
            c::SINK_RAM_KERNEL => Kind::Kernel,
            c::SINK_RAM_RESERVED => Kind::Reserved,
            c::SINK_RAM_UNUSABLE => Kind::Unusable,
            c::SINK_TARGET_GPU => Kind::Gpu,
            c::SINK_GPU_DECLARED => Kind::GpuDeclared,
            c::SINK_GPU_RESERVED => Kind::GpuReserved,
            _ => bail!("unknown inventory kind {v}"),
        })
    }

    /// Whether a session may name an entry of this kind.
    pub fn is_target(self) -> bool {
        matches!(self, Kind::Ram | Kind::Disk | Kind::Gpu)
    }
}

/// One Inventory entry.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize)]
pub struct Entry {
    pub kind: Kind,
    /// "" = the source's own machine, else the downstream sink ("dpu0", "dpu0/bmc0").
    pub node: String,
    /// "ram", a device path, or a RAM map entry's name ("System RAM", ...).
    pub name: String,
    pub base: u64,
    pub size: u64,
    pub sector: u32,
}

/// SessionInit as the verifier sends it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SessionInit {
    pub session: u32,
    pub node: String,
    pub target: String,
    pub base: u64,
    pub size: u64,
    pub chunk_blocks: u32,
    pub seed: Seed,
    pub algo: u8,
}

/// A frame the source sends the verifier.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Reply {
    Inventory(Vec<Entry>),
    InitAck { ok: bool, error: String },
    /// (phys_base, block_count) runs.
    Coverage(Vec<(u64, u64)>),
    Progress { session: u32, bytes_done: u64 },
    Label(Label),
    Error(String),
}

// ── encoding ──────────────────────────────────────────────────────────────

fn put_str(out: &mut Vec<u8>, s: &str, max: u64) -> Result<()> {
    ensure!((s.len() as u64) < max, "string {s:?} longer than {} bytes", max - 1);
    out.extend_from_slice(&(s.len() as u16).to_be_bytes());
    out.extend_from_slice(s.as_bytes());
    Ok(())
}

pub fn enc_inventory_request(version: u16) -> Vec<u8> {
    version.to_be_bytes().to_vec()
}

pub fn enc_session_init(i: &SessionInit) -> Result<Vec<u8>> {
    let mut b = Vec::with_capacity(64 + i.node.len() + i.target.len());
    b.extend_from_slice(&i.session.to_be_bytes());
    put_str(&mut b, &i.node, c::SINK_NODE_MAX)?;
    put_str(&mut b, &i.target, c::SINK_NAME_MAX)?;
    b.extend_from_slice(&i.base.to_be_bytes());
    b.extend_from_slice(&i.size.to_be_bytes());
    b.extend_from_slice(&i.chunk_blocks.to_be_bytes());
    b.extend_from_slice(&i.seed);
    b.push(i.algo);
    Ok(b)
}

pub fn enc_challenge(session: u32, block_index: u64) -> Vec<u8> {
    let mut b = Vec::with_capacity(12);
    b.extend_from_slice(&session.to_be_bytes());
    b.extend_from_slice(&block_index.to_be_bytes());
    b
}

pub fn enc_finish(action: u8, reason: &str) -> Result<Vec<u8>> {
    let mut b = vec![action];
    // A long reason (many failed sessions) is cut rather than refused.
    let mut r = reason;
    while r.len() as u64 >= c::SINK_REASON_MAX {
        let mut end = c::SINK_REASON_MAX as usize - 1;
        while !r.is_char_boundary(end) {
            end -= 1;
        }
        r = &r[..end];
    }
    put_str(&mut b, r, c::SINK_REASON_MAX)?;
    Ok(b)
}

// ── decoding ──────────────────────────────────────────────────────────────

struct Rd<'a> {
    p: &'a [u8],
}

impl<'a> Rd<'a> {
    fn take(&mut self, n: usize) -> Result<&'a [u8]> {
        ensure!(self.p.len() >= n, "payload too short");
        let (a, b) = self.p.split_at(n);
        self.p = b;
        Ok(a)
    }
    fn u8(&mut self) -> Result<u8> {
        Ok(self.take(1)?[0])
    }
    fn u16(&mut self) -> Result<u16> {
        Ok(u16::from_be_bytes(self.take(2)?.try_into()?))
    }
    fn u32(&mut self) -> Result<u32> {
        Ok(u32::from_be_bytes(self.take(4)?.try_into()?))
    }
    fn u64(&mut self) -> Result<u64> {
        Ok(u64::from_be_bytes(self.take(8)?.try_into()?))
    }
    fn str(&mut self, max: u64) -> Result<String> {
        let n = self.u16()? as usize;
        ensure!((n as u64) < max, "string longer than {} bytes", max - 1);
        Ok(String::from_utf8_lossy(self.take(n)?).into_owned())
    }
    fn done(&self) -> Result<()> {
        ensure!(self.p.is_empty(), "{} trailing bytes", self.p.len());
        Ok(())
    }
}

/// Decode one frame from the source.
pub fn decode(ty: u8, payload: &[u8]) -> Result<Reply> {
    let mut r = Rd { p: payload };
    let reply = match ty as u64 {
        c::SINK_MSG_INVENTORY => {
            let n = r.u32()? as u64;
            ensure!(n <= c::SINK_MAX_TARGETS, "inventory of {n} entries");
            let mut v = Vec::with_capacity(n as usize);
            for _ in 0..n {
                v.push(Entry {
                    kind: Kind::from_wire(r.u8()?)?,
                    node: r.str(c::SINK_NODE_MAX)?,
                    name: r.str(c::SINK_NAME_MAX)?,
                    base: r.u64()?,
                    size: r.u64()?,
                    sector: r.u32()?,
                });
            }
            Reply::Inventory(v)
        }
        c::SINK_MSG_INIT_ACK => Reply::InitAck {
            ok: r.u8()? as u64 == c::SINK_STATUS_OK,
            error: r.str(c::SINK_REASON_MAX)?,
        },
        c::SINK_MSG_COVERAGE => {
            let n = r.u32()? as u64;
            ensure!(n <= c::SINK_MAX_REGIONS, "coverage of {n} regions");
            let mut v = Vec::with_capacity(n as usize);
            for _ in 0..n {
                v.push((r.u64()?, r.u64()?));
            }
            Reply::Coverage(v)
        }
        c::SINK_MSG_PROGRESS => Reply::Progress { session: r.u32()?, bytes_done: r.u64()? },
        c::SINK_MSG_LABEL => Reply::Label(r.take(LABEL_BYTES)?.try_into()?),
        c::SINK_MSG_ERROR => Reply::Error(r.str(c::SINK_REASON_MAX)?),
        _ => bail!("unexpected frame type 0x{ty:02x}"),
    };
    r.done().with_context(|| format!("frame type 0x{ty:02x}"))?;
    Ok(reply)
}

// ── the connection ────────────────────────────────────────────────────────

/// How long the verifier waits for any frame before declaring the source
/// gone.  A generating source sends Progress every second; the longest
/// legitimate silences are a downstream sink still booting at inventory time
/// (the source waits 60 s for it) and the flush or fsync after a stream.
pub const RECV_TIMEOUT: Duration = Duration::from_secs(300);

pub struct Conn {
    s: TcpStream,
}

impl Conn {
    pub fn connect(addr: &str) -> Result<Conn> {
        let s = TcpStream::connect(addr).with_context(|| format!("connecting to {addr}"))?;
        s.set_nodelay(true)?;
        s.set_read_timeout(Some(RECV_TIMEOUT))?;
        Ok(Conn { s })
    }

    pub fn send(&mut self, ty: u64, payload: &[u8]) -> Result<()> {
        let mut f = Vec::with_capacity(5 + payload.len());
        f.push(ty as u8);
        f.extend_from_slice(&(payload.len() as u32).to_be_bytes());
        f.extend_from_slice(payload);
        self.s.write_all(&f).context("connection lost sending")
    }

    pub fn recv(&mut self) -> Result<Reply> {
        let mut h = [0u8; 5];
        self.s.read_exact(&mut h).context("connection lost waiting for the source")?;
        let len = u32::from_be_bytes(h[1..].try_into()?) as u64;
        ensure!(len <= c::SINK_MAX_CTRL_BODY, "frame of {len} bytes");
        let mut p = vec![0u8; len as usize];
        self.s.read_exact(&mut p).context("connection lost mid-frame")?;
        decode(h[0], &p)
    }
}

// ── cross-check against the C encoders (pose-sink/src/sink_proto.c) ───────

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::raw::c_int;

    const NODE: usize = c::SINK_NODE_MAX as usize;
    const NAME: usize = c::SINK_NAME_MAX as usize;

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct CTarget {
        kind: u8,
        node: [u8; NODE],
        name: [u8; NAME],
        base: u64,
        size: u64,
        sector: u32,
    }
    #[repr(C)]
    struct CInventory {
        count: u32,
        targets: [CTarget; c::SINK_MAX_TARGETS as usize],
    }
    #[repr(C)]
    struct CSessionInit {
        session: u32,
        node: [u8; NODE],
        target: [u8; NAME],
        base: u64,
        size: u64,
        chunk_blocks: u32,
        seed: Seed,
        algo: u8,
    }
    #[repr(C)]
    struct CCoverage {
        count: u32,
        regions: [[u64; 2]; c::SINK_MAX_REGIONS as usize],
    }

    extern "C" {
        fn sink_enc_inventory_request(buf: *mut u8, cap: usize, v: u16) -> c_int;
        fn sink_enc_inventory(buf: *mut u8, cap: usize, inv: *const CInventory) -> c_int;
        fn sink_enc_session_init(buf: *mut u8, cap: usize, i: *const CSessionInit) -> c_int;
        fn sink_enc_init_ack(buf: *mut u8, cap: usize, status: u8, err: *const u8) -> c_int;
        fn sink_enc_coverage(buf: *mut u8, cap: usize, cov: *const CCoverage) -> c_int;
        fn sink_enc_progress(buf: *mut u8, cap: usize, s: u32, done: u64) -> c_int;
        fn sink_enc_challenge(buf: *mut u8, cap: usize, s: u32, idx: u64) -> c_int;
        fn sink_enc_label(buf: *mut u8, cap: usize, l: *const u8) -> c_int;
        fn sink_enc_finish(buf: *mut u8, cap: usize, a: u8, reason: *const u8) -> c_int;
        fn sink_enc_error(buf: *mut u8, cap: usize, reason: *const u8) -> c_int;
    }

    fn cstr<const N: usize>(s: &str) -> [u8; N] {
        let mut a = [0u8; N];
        a[..s.len()].copy_from_slice(s.as_bytes());
        a
    }

    /// Run a C encoder into a fresh buffer and return its payload.
    fn c_enc(f: impl FnOnce(*mut u8, usize) -> c_int) -> Vec<u8> {
        let mut buf = vec![0u8; c::SINK_MAX_CTRL_BODY as usize];
        let n = f(buf.as_mut_ptr(), buf.len());
        assert!(n >= 0, "C encoder failed");
        buf.truncate(n as usize);
        buf
    }

    #[test]
    fn requests_match_c() {
        let init = SessionInit {
            session: 7,
            node: "dpu0/bmc0".into(),
            target: "/dev/nvme0n1".into(),
            base: 0x2c000_0000,
            size: 64 << 20,
            chunk_blocks: 1 << 18,
            seed: [0xa5; SEED_BYTES],
            algo: c::SINK_ALGO_AES_PRF as u8,
        };
        let ci = CSessionInit {
            session: 7,
            node: cstr("dpu0/bmc0"),
            target: cstr("/dev/nvme0n1"),
            base: init.base,
            size: init.size,
            chunk_blocks: init.chunk_blocks,
            seed: init.seed,
            algo: init.algo,
        };
        assert_eq!(enc_session_init(&init).unwrap(), c_enc(|b, n| unsafe { sink_enc_session_init(b, n, &ci) }));
        assert_eq!(enc_inventory_request(2), c_enc(|b, n| unsafe { sink_enc_inventory_request(b, n, 2) }));
        assert_eq!(enc_challenge(3, 1 << 40), c_enc(|b, n| unsafe { sink_enc_challenge(b, n, 3, 1 << 40) }));
        assert_eq!(
            enc_finish(0, "proof accepted").unwrap(),
            c_enc(|b, n| unsafe { sink_enc_finish(b, n, 0, b"proof accepted\0".as_ptr()) })
        );
    }

    #[test]
    fn replies_from_c_decode() {
        let mut inv: Box<CInventory> = unsafe { Box::new(std::mem::zeroed()) };
        let rows = [
            (c::SINK_TARGET_RAM, "", "ram", 0x2c000_0000u64, 1865u64 << 20, 0u32),
            (c::SINK_TARGET_DISK, "dpu0", "/dev/nvme0n1", 0, 10 << 30, 512),
            (c::SINK_RAM_KERNEL, "dpu0", "System RAM", 0x4000_0000, 10 << 30, 0),
            (c::SINK_RAM_RESERVED, "", "ACPI Tables", 0x7f00_0000, 64 << 10, 0),
        ];
        for (i, &(k, node, name, base, size, sector)) in rows.iter().enumerate() {
            inv.targets[i] =
                CTarget { kind: k as u8, node: cstr(node), name: cstr(name), base, size, sector };
        }
        inv.count = rows.len() as u32;
        let p = c_enc(|b, n| unsafe { sink_enc_inventory(b, n, &*inv) });
        let Reply::Inventory(v) = decode(c::SINK_MSG_INVENTORY as u8, &p).unwrap() else { panic!() };
        assert_eq!(v.len(), 4);
        assert_eq!(v[1], Entry { kind: Kind::Disk, node: "dpu0".into(), name: "/dev/nvme0n1".into(), base: 0, size: 10 << 30, sector: 512 });
        assert_eq!(v[3].kind, Kind::Reserved);
        assert!(!v[2].kind.is_target());

        let mut cov: Box<CCoverage> = unsafe { Box::new(std::mem::zeroed()) };
        cov.count = 1;
        cov.regions[0] = [0x2c000_0000, 1 << 21];
        let p = c_enc(|b, n| unsafe { sink_enc_coverage(b, n, &*cov) });
        assert_eq!(decode(c::SINK_MSG_COVERAGE as u8, &p).unwrap(), Reply::Coverage(vec![(0x2c000_0000, 1 << 21)]));

        let p = c_enc(|b, n| unsafe { sink_enc_progress(b, n, 4, 12345) });
        assert_eq!(decode(c::SINK_MSG_PROGRESS as u8, &p).unwrap(), Reply::Progress { session: 4, bytes_done: 12345 });

        let p = c_enc(|b, n| unsafe { sink_enc_init_ack(b, n, c::SINK_STATUS_ERROR as u8, b"no such target 'x'\0".as_ptr()) });
        assert_eq!(decode(c::SINK_MSG_INIT_ACK as u8, &p).unwrap(), Reply::InitAck { ok: false, error: "no such target 'x'".into() });

        let l = [7u8; LABEL_BYTES];
        let p = c_enc(|b, n| unsafe { sink_enc_label(b, n, l.as_ptr()) });
        assert_eq!(decode(c::SINK_MSG_LABEL as u8, &p).unwrap(), Reply::Label(l));

        let p = c_enc(|b, n| unsafe { sink_enc_error(b, n, b"boom\0".as_ptr()) });
        assert_eq!(decode(c::SINK_MSG_ERROR as u8, &p).unwrap(), Reply::Error("boom".into()));
    }

    #[test]
    fn strict_decoding() {
        assert!(decode(c::SINK_MSG_PROGRESS as u8, &[0; 11]).is_err()); // short
        assert!(decode(c::SINK_MSG_PROGRESS as u8, &[0; 13]).is_err()); // trailing
        assert!(decode(c::SINK_MSG_LABEL as u8, &[0; 33]).is_err());
        assert!(decode(c::SINK_MSG_INVENTORY as u8, &[0, 0, 0, 1, 9, 0, 0, 0, 0]).is_err()); // bad kind
        assert!(decode(0x10, &[0, 2]).is_err()); // a request is not a reply
    }

    #[test]
    fn long_finish_reason_is_cut() {
        let p = enc_finish(0, &"x".repeat(1000)).unwrap();
        assert_eq!(p.len(), 1 + 2 + c::SINK_REASON_MAX as usize - 1);
    }
}
